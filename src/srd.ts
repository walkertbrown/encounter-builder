export const SRD_MONSTERS: SrdMonster[] = ROWS.map(([name, cr, kind, ac, hp, init]) => ({ name, cr, kind, ac, hp, init }));

const key = (s: string) => s.toLowerCase().replace(/[’']/g, "'").replace(/\s+/g, ' ').trim();
const BY_NAME = new Map(SRD_MONSTERS.map((m) => [key(m.name), m]));

/** The SRD monster a name means, if any: "owlbear", "Goblin Warriors" and "Wolves" all count. */
export function srdMonster(name: string): SrdMonster | undefined {
	const k = key(name);
	if (!k) return undefined;
	const tries = [k, k.replace(/ves$/, 'f'), k.replace(/ies$/, 'y'), k.replace(/es$/, ''), k.replace(/s$/, '')];
	for (const t of tries) {
		const m = BY_NAME.get(t);
		if (m) return m;
	}
	return undefined;
}

/** The SRD monster a creature line names, by its name or the note it links to. */
export function srdFor(l: Line): SrdMonster | undefined {
	return srdMonster(l.name) ?? (l.link ? srdMonster(l.link.split('#')[0]!.split('/').pop()!.replace(/\.md$/i, '')) : undefined);
}
